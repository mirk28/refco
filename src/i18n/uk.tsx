/**
 * Interface texts in Ukrainian. Same keys as `en.tsx`.
 *
 * Wording: «реферальний код» for referral code (main keyword, the name follows: «реферальний код Binance»),
 * «код запрошення» and «реферальне посилання» as second terms, «криптобіржа» / «біржа» for the exchange, «комісії»
 * for fees, «спот» / «ф'ючерси» for the markets, polite «ви» in lower case. Exchange names stay Latin and are never
 * declined; a bare name agrees with «біржа» (feminine). The Cyrillic spelling of a name follows it in brackets only in
 * the title, the H1 and the keywords (`withReading`). Numbers with a decimal comma and a space for thousands (0,02%,
 * 10 000 USDT, $34,1 млрд). Counts with a variable number go through `slavicCount`. Field and button names of the
 * exchanges stay in English, because only the English interface was checked.
 */

const benefit = (e: Exchange) => e.feeDiscount || e.bonusHeadline;
/** "A, B та C" – «та» never changes with the sound next to it. */
const list = (items: string[]) => (items.length <= 1 ? items.join("") : `${items.slice(0, -1).join(", ")} та ${items[items.length - 1]}`);
const shortLeverage = (e: Exchange) => e.maxLeverage.replace(/\s*\(.*\)/, "");
/** Lower-cases a first Cyrillic letter only ("До 150x" → "до 150x"); Latin names and numbers stay as they are. */
const lcCyr = (s: string) => (/^[А-ЯҐЄІЇ]/.test(s) ? s.charAt(0).toLocaleLowerCase("uk-UA") + s.slice(1) : s);
/** A step title as a sentence in a running answer. */
const asSentence = (s: string) => (/[.!?:]$/.test(s.trim()) ? s.trim() : `${s.trim()}.`);
/** A number in Ukrainian notation: 1234.5 → "1 234,5" (an ordinary space; a script makes it no-break). */
const ukNumber = (n: number, digits: number) => {
  const [int, dec] = n.toFixed(digits).split(".");
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  return dec ? `${grouped},${dec}` : grouped;
};
/** The all-Cyrillic spelling for search queries: «бінанс»; an all-capital one («ОКХ») stays as it is. */
const cyrQuery = (slug: string) => {
  const r = readingOf(slug, "uk");
  if (!r) return undefined;
  return r === r.toLocaleUpperCase("uk-UA") ? r : r.toLocaleLowerCase("uk-UA");
};
/** What the exchange itself calls the code: an English interface term in “…”, a Ukrainian one in «…». */
const ownName = (e: Exchange) => {
  const cn = e.referral.codeName.trim();
  return /^[\x20-\x7E]+$/.test(cn) ? `Сама ${e.name} називає його “${cn}”.` : `Сама ${e.name} називає його «${cn}».`;
};

