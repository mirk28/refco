/**
 * Interface texts in Russian. Same keys as `en.tsx`.
 *
 * Wording: «реферальный код» for referral code (main keyword, the name follows: «реферальный код Binance»),
 * «код приглашения» and «реферальная ссылка» as second terms, «криптобиржа» / «биржа» for the exchange, «комиссии»
 * for fees, «спот» / «фьючерсы» for the markets, «вы» in lower case. Exchange names stay Latin and are never declined;
 * a bare name agrees with «биржа» (feminine), and where the case would stay unclear «биржа» goes in front. The Cyrillic
 * spelling of a name follows it in brackets only in the title, the H1, the lead and the keywords (`withReading`).
 * «е» for «ё» except «всё». Numbers with a decimal comma and a space for thousands (0,02%, 10 000 USDT, $34,1 млрд).
 * Dashes are em dashes with spaces («Да — …»). Counts with a variable number go through `slavicCount`. Field and button
 * names of the exchanges stay in English in “…”, because only the English interface was checked.
 */

const benefit = (e: Exchange) => e.feeDiscount || e.bonusHeadline;
/** "A, B и C" – no comma before «и». */
const list = (items: string[]) => (items.length <= 1 ? items.join("") : `${items.slice(0, -1).join(", ")} и ${items[items.length - 1]}`);
const shortLeverage = (e: Exchange) => e.maxLeverage.replace(/\s*\(.*\)/, "");
/** Lower-cases a first Cyrillic letter only ("До 150x" → "до 150x"); Latin names and numbers stay as they are. */
const lcCyr = (s: string) => (/^[А-ЯЁ]/.test(s) ? s.charAt(0).toLocaleLowerCase("ru-RU") + s.slice(1) : s);
/** A step title as a sentence in a running answer. */
const asSentence = (s: string) => (/[.!?:]$/.test(s.trim()) ? s.trim() : `${s.trim()}.`);
/** A number in Russian notation: 34.09 → "34,09", 1234 → "1 234". */
const ruNumber = (n: number, digits: number) => n.toLocaleString("ru-RU", { minimumFractionDigits: digits, maximumFractionDigits: digits });
/** The all-Cyrillic spelling for search queries: «бинанс»; an all-capital one («ОКХ») stays as it is. */
const cyrQuery = (slug: string) => {
  const r = readingOf(slug, "ru");
  if (!r) return undefined;
  return r === r.toLocaleUpperCase("ru-RU") ? r : r.toLocaleLowerCase("ru-RU");
};
/** What the exchange itself calls the code: an English interface term in “…”, a Russian one in «…». */
const ownName = (e: Exchange) => {
  const cn = e.referral.codeName.trim();
  return /^[\x20-\x7E]+$/.test(cn) ? `На самой бирже ${e.name} его называют “${cn}”.` : `На самой бирже ${e.name} его называют «${cn}».`;
};

